/*
 * 接线模型：
 *   段 a~g (+dp) ── 各串 180Ω ── RP2350 GPIO（**拉电流**，段为阳极）
 *   位选 1/2（共阴=阴极）── NPN 集电极，发射极接 GND，基极串 1kΩ 到 GPIO
 *
 * ★★ 为什么位选必须用三极管，不能直接拿 GPIO 灌：
 *   一位点亮时最多 8 段同时导通，每段约 7 mA → 阴极要灌 56 mA。
 *   RP2350 单个 pad 的驱动能力只有 ~8 mA（可配 2/4/8/12 mA 档），
 *   直接灌会烧 pad 或者亮度惨不忍睹、还干扰旁边的 I2S 信号。
 *
 * ★ 段线选 GPIO15~22 **连续 8 根**：
 *   RP2350 的 SIO 有 32 位掩码寄存器 gpio_set/gpio_clr（覆盖 GPIO0~31），
 *   所以整组段线可以用**一次 32 位写**更新，扫描中断里很省时间：
 *       sio_hw->gpio_set = seg_on_mask;   // 要点亮的段
 *       sio_hw->gpio_clr = seg_off_mask;  // 要熄灭的段
 *   散开分配就没这个好处了。
 *
 * ★ 段限流电阻 180Ω（@3.3V，红光 Vf≈2.0V）：
 *   峰值 (3.3-2.0-0.2)/180 ≈ 6.1 mA，两位 50% 占空 → 平均 3 mA/段
 *   觉得暗就换 120Ω（峰值 9 mA，接近 pad 上限，不要再小）
 */
