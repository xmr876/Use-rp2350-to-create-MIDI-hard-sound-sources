/* 电源                                                                */
/* ================================================================== */
/*
 * ★ Pico 2 模块自带 USB 接口、VBUS→VSYS 的肖特基、3.3V buck、复位键、
 *   BOOTSEL 键、晶振、调试口。**载板不需要再画这些**。
 *
 * 载板从 Pico 2 取电：
 *   3V3 排针  ── 3.3V 网络 ──┬── PCM5102A 模块 VIN   ★ 必须 3.3V，绝不能 5V
 *                            ├── 32MB SPI Flash VCC
 *                            ├── 6N138 光耦 VCC（接 3.3V，见下）
 *                            └── 数码管段驱动 / NPN 位选
 *
 * 电流预算（3V3 轨）：
 *   PCM5102A 模块   ~30 mA
 *   SPI Flash        ~15 mA（编程时峰值 25 mA）
 *   数码管           ~60 mA（8 段 × 7 mA，50% 占空）
 *   6N138 光耦       ~10 mA
 *   合计            ~115 mA   ← Pico 2 的 3V3 输出能力足够（SMPS 可到 1A 级）
 *
 * ★ 外部 5V 供电焊盘（可选，脱离电脑当独立音源用）：
 *   接到 Pico 2 的 **VSYS** 脚（不是 VBUS），串一颗 SS34。
 *   VSYS 的工作范围 1.8~5.5V，内部 buck 会自己降压。
 *   ★ 千万不要把外部 5V 直接灌到 3V3 脚上 —— 会打坏 Pico 2 和所有外设。
 *
 * ★ USB-C/micro-USB 受电端的 CC 下拉：**Pico 2 模块已经做好了**，
 *   载板用 Pico 2 的 USB 座，所以不用管。这也是用模块的好处之一。
 */
#define BOARD_VIN_MILLIVOLT   5000u
#define BOARD_3V3_MILLIVOLT   3300u

/* VBUS 检测：Pico 2 模块内部已经把 VBUS 分压接到 **GPIO24**，
 * 载板不用外接分压。用 SDK 的 vbus_present()（pico_board pico2 已配好）。
 * ★ GPIO24/25 在 Pico 2 上**没有引到排针**（24=VBUS sense，25=LED），
 *   所以这两脚不能拿来做别的用。 */
#define PIN_VBUS_SENSE        -1   /* -1 = 用模块内部（vbus_present()） */

/* ================================================================== */
/* PCM5102A 软静音控制（XSMT）                                          */
/* ================================================================== */
/*
 * ★ 数据手册规定了关机顺序，不遵守会有可闻爆音：
 *     断电前 ≥150 t_S + 0.2ms 把 XSMT 拉低
 *     断电前 3ms 停掉 SCK/BCK/LRCK
 *
 * 现成模块上 XSMT 通常已被上拉电阻钳在"不静音"，不要硬接 GPIO 去打架。
 * 若你的模块把 XSMT 引出来了且没有板上上拉，就接到这个脚由固件控制。
 * 模块未引出 / 已有上拉 → 填 -1，固件会跳过静音逻辑。
 *
 * 注意：XSMT 的"外部欠压模式"只在 DVDD = 3.3V 时可用（手册 p.23）。
 */
#define PIN_DAC_XSMT          -1   /* -1 = 不控制（用现成模块的默认上拉） */

/* ================================================================== */
/* I2S → PCM5102A 模块                                                  */
/* ================================================================== */
/*
 * 模块丝印（以实物为准）：
 *   控制排: VIN GND FLT DEMP XSMT FMT SCK
 *   信号排: VIN GND BCK DIN LRCK
 * 只接 5 根线：VIN / GND / BCK / DIN / LRCK
 *
 * ★ SCK 必须接 GND —— 选内部 PLL，从 BCK 重建主时钟，省掉 MCLK。
 * ★ VIN 必须给 3.3V（不是 5V）：PCM5102A 绝对最大额定值 3.9V，5V 会打坏。
 * ★ FLT / DEMP / XSMT / FMT 模块已配好默认值，固件与硬件都不用管。
 *
 * ★★ 引脚顺序是硬约束，不要随手改：
 *   i2s.pio 用 `.side_set 2`，其中
 *       side bit 0 → LRCK
 *       side bit 1 → BCK
 *   而 out 引脚 = side_set_base + 2 → DIN
 *   所以必须满足 **LRCK、BCK、DIN 是连续的三个 GPIO**。
 *   i2s.c 里有编译期断言检查这一点，不满足会直接编译报错。
 *
 *   当前分配：LRCK=12, BCK=13, DIN=14 ✓ 连续
 *   （在 Pico 2 排针上，GPIO12/13/14 是连续的三根，接线看着也舒服）
 */
#define PIN_I2S_LRCK          12   /* side-set bit 0 —— 必须是最低那个 */
#define PIN_I2S_BCK           13   /* side-set bit 1 */
#define PIN_I2S_DIN           14   /* out，= PIN_I2S_LRCK + 2 */

/* 供 i2s.c 做编译期校验 */
#define PIN_I2S_SIDESET_BASE  PIN_I2S_LRCK
#define PIN_I2S_OUT_BASE      PIN_I2S_DIN

/* ================================================================== */
/* 音色库 Flash：**就是那片魔改成 16MB 的 CS0 Flash**                    */
/* ================================================================== */
/*
 * ★★ 本方案不需要第二片 Flash。
 *
 *   音色库和固件住在同一片 16MB Flash 上，全部走 QMI（CS0）。
 *   这意味着**音色库是内存映射的** —— 读一个采样点就是读一个指针：
 *
 *       const int16_t *p = (const int16_t *)(XIP_BASE + zone->sample_off);
 *
 *   XIP 缓存（16KB，2 路组相联）自动处理，**一行业务驱动代码都不用写**：
 *     · 不需要 SPI 驱动
 *     · 不需要 DMA 搬运
 *     · 不需要 QMI Direct Serial Mode
 *       （也就没有"direct 模式期间不能执行 flash 里的代码"那类致命约束）
 *     · 不需要 __not_in_flash_func
 *     · 不受勘误 E14（CS1 pad 配置）影响
 *
 * ★ 为什么 16MB 可以，32MB 不行：
 *   RP2350 的 OTP 字段 FLASH_DEVINFO.CS0_SIZE 决定 XIP 窗口大小。
 *   SDK 里的原文：
 *     "When BOOT_FLAGS0_FLASH_DEVINFO_ENABLE is not set,
 *      a default of 12 (16 MiB) is used."
 *   也就是**一片没烧过 OTP 的 RP2350，bootrom 默认就认为 CS0 上有 16MiB**，
 *   XIP 窗口 = 0x10000000..0x10FFFFFF。
 *   魔改成 16MB **正好等于这个默认值** —— 不用烧 OTP，UF2 也能写满整片。
 *   32MB 就超出这个窗口了（CS0_SIZE 枚举值 SDK 只列到 12=16MB），
 *   要烧 OTP 且 13 这个值未文档化，风险大得多。
 *
 * ★ 带宽：XIP 走 QSPI，bootrom 已把它配成 75MHz（PICO_FLASH_SPI_CLKDIV=2）。
 *   48 复音满负载（ADPCM 4bit @48kHz）需要约 1.15 MB/s，
 *   四线 QSPI @75MHz 的裸带宽是几十 MB/s，余量极大；
 *   再加上 16KB XIP 缓存，循环段几乎全部命中缓存。
 *
 * ★ 编译时必须传 -DPICO_FLASH_SIZE_BYTES=16777216，
 *   否则 flash_range_erase/program 的边界检查会把 4MB 以上判为越界。 */

#define BOARD_FLASH_TOTAL_BYTES   (16u * 1024u * 1024u)   /* 16 MB */
#define BOARD_LIB_BASE            (0x40000u)              /* 音色库起点 */
#define BOARD_FW_RESERVE          (0x80000u)              /* 固件区预留 512KB */
#define BOARD_XIP_BASE            (0x10000000u)

/* 音色库在 XIP 视角的地址（= 0x10040000），固件里访问采样用这个 */
#define BOARD_LIB_XIP_ADDR        (BOARD_XIP_BASE + BOARD_LIB_BASE)

/* 不需要第二片芯片的任何引脚。原来计划给 SPI Flash 的 GPIO2~5 全部空闲。 */

/* ================================================================== */
/* MIDI 输入（6N138/6N139 光耦，输出集电极开路 → 1k 上拉到 3.3V）        */
/* ================================================================== */
/*
 * ★★ 关于光耦选型（这里踩过坑，记下来）：
 *   - **6N317 这个型号不存在**。它是 6N137 的笔误/数字错位。
 *   - **6N137 不能直接用于 MIDI 输入**：它是逻辑输出光耦，
 *     保证工作需要 ≥6.3 mA 的 LED 电流；而 MIDI 电气规范（CA-033）
 *     要求接收端在 **5 mA 以下**就能可靠翻转（发送端 2×220Ω @5V）。
 *     用 6N137 的症状是"有些设备能收，有些完全收不到"。
 *   - **该用 6N138 / 6N139 / PC-900V / H11L1**（达林顿输出，CTR > 300%，
 *     零点几毫安就能翻转），这是 MIDI 事实标准。
 *
 * ★ 6N138 DIP-8 引脚：
 *     1 NC   2 Anode   3 Cathode   4 NC
 *     5 GND  6 VO(OC)  7 VB(Base)  8 VCC
 *   接法：
 *     DIN-5 pin4 ──220Ω── 2(Anode)   ← 注意是 pin4 供电流
 *     DIN-5 pin5 ───────── 3(Cathode)
 *     5(GND) ── GND
 *     8(VCC) ── 3.3V
 *     6(VO)  ── 1kΩ ── 3.3V        ★ 1k，不是 4.7k/10k
 *            └──────── PIN_MIDI_RX
 *     7(VB)  ── 4.7kΩ ── GND       ★ 加速关断，不加会限速
 *   DIN-5 pin2(屏蔽) ── 100nF ── GND（或直接悬空）
 *
 *   ★ 上拉为什么必须是 1k 而不是常见的 10k：
 *     6N138 的输出是达林顿，等效输出电容大，10k 上拉时上升沿
 *     要几十微秒，31250 bps（位宽 32µs）直接糊掉。
 *     1k 时上升时间约 1~2µs，干净。
 *
 * ★ 极性：MIDI 空闲时电流环**无电流**（发送端 TX 为高），
 *   光耦不导通 → VO 被上拉到高 → UART 空闲高 ✓
 *   起始位 = 有电流 → 光耦导通 → VO 低 ✓
 *   所以**极性正好，不要加反相器**。
 *
 * ★ UART 实例：用 UART1 的 **AUX** 功能（F11）。
 *   RP2350 多了 GPIO_FUNC_UART_AUX = 11 这一档：
 *     GPIO10 F11 = UART1 TX
 *     GPIO11 F11 = UART1 RX
 *   代码里用 SDK 的 UART_FUNCSEL_NUM(uart1, pin) 宏取功能号，
 *   不写死数字 —— 那个宏就是 (gpio & 0x2) ? UART_AUX : UART，
 *   手写容易写错。
 *
 * ★★★ 这里踩过一个**从第一天就存在、而且极难发现**的坑 ★★★
 *
 *   上面那两行（GPIO10=TX、GPIO11=RX）是**对的**，
 *   但最初下面这两个 #define 把它们**写反了**：
 *         PIN_MIDI_RX = 10    ← 错！GP10 是 TX
 *         PIN_MIDI_TX = 11    ← 错！GP11 是 RX
 *   于是光耦输出接到了 UART 的 **TX** 脚上。
 *
 *   为什么极难发现：
 *     · 注释里写着"GPIO10/11 只映射到 UART1" —— 这句本身没错，
 *       但收发方向反了，看注释查不出来；
 *     · TX 脚空闲时**主动输出高电平**，把光耦的输出顶住，
 *       所以现象是"光耦在翻转、走线导通、但一个字节也收不到"；
 *     · 万用表量 光耦VO 对 3V3 会读到 **0Ω** —— 那是 RP2350 的
 *       输出驱动器，很容易被误判成"量法不对"或"短路"。
 *
 *   RP2350 的 UART1 引脚分组（以官方引脚表为准）：
 *       TX : 4, 8, 20, 24       RX : 5, 9, 21, 25
 *       CTS(aux 模式下当 TX): 6, 10, 22, 26
 *       RTS(aux 模式下当 RX): 7, 11, 23, 27
 *   → **GP10 只能做 TX，GP11 只能做 RX**，没有别的选择。
 *
 * ★ UART 配置：8N1、无校验、31250 波特。
 */
#define PIN_MIDI_RX           11   /* ★★★ 必须 11，不能是 10 ★★★
                                    *
                                    *   RP2350 的 UART1 引脚分组（官方引脚表）：
                                    *       TX : 4, 8, 20, 24     RX : 5, 9, 21, 25
                                    *       CTS（AUX 模式下当 TX）: 6, 10, 22, 26
                                    *       RTS（AUX 模式下当 RX）: 7, 11, 23, 27
                                    *   → **GP10 只能做 TX，GP11 才是 RX。**
                                    *
                                    *   载板最初把光耦接在 GP10 上（= UART 的**发送**脚），
                                    *   所以怎么都收不到；TX 空闲时输出高电平还会把
                                    *   光耦顶住（现场量到"VO 稳定 3.3V、对 3V3 电阻 0Ω"）。
                                    *
                                    *   中间试过用 PIO 在 GP10 上软件实现 UART —— 时序能对上，
                                    *   但一进主循环就冻结，原因始终没查到。
                                    *
                                    *   → 飞一根线把光耦输出从 GP10 挪到 GP11，用回硬件 UART。
                                    *     中断驱动、不占主循环、没有阻塞调用。
                                    *   ★ 上拉电阻（1kΩ 到 3V3）挂在那根线上，跟着挪。 */
#define PIN_MIDI_TX           10   /* GP10 是 UART1 的 TX（AUX 模式）。
                                    *   本工程不做 MIDI THRU，所以不驱动它 ——
                                    *   但**一定要设成 UART 功能号**，
                                    *   否则残留状态可能干扰。 */

